//! 멈춤 안내: 엔진의 멈춤 문구를 멈춘 이유와 다음 할 일로 바꾼다.
//! 엔진 결과에는 멈춤 종류가 없어(kind 는 "멈춤" 하나) 문구에 든 키워드로 흔한 경우를 묶고,
//! 맞는 게 없으면 첫 줄과 기본 안내를 쓴다.

pub struct Guide {
    pub reason: String,
    pub next: String,
}

fn g(reason: &str, next: &str) -> Guide {
    Guide { reason: reason.to_string(), next: next.to_string() }
}

/// 문구에 키워드가 하나라도 들었는지.
fn has(m: &str, keys: &[&str]) -> bool {
    keys.iter().any(|k| m.contains(k))
}

pub fn stop_guide(message: &str) -> Guide {
    let m = message;
    let lower = m.to_lowercase();

    // 구체적인 경우를 먼저 건다(위에서 아래로 처음 맞는 것).
    if has(m, &["다른 저장소 같습니다"]) {
        return g(
            "번들의 저장소 이름과 고른 폴더의 저장소가 달라 보이고, 번들이 기대는 커밋이 그 폴더에 없습니다.",
            "목록의 [저장소 바꾸기…]로 이 번들의 저장소 폴더를 다시 골라 주세요. 아무것도 바꾸지 않았습니다.",
        );
    }
    if has(m, &["git 저장소가 아닙", "저장소가 아닙", "저장소가 아니다"]) {
        return g("고른 폴더가 git 저장소가 아닙니다.", "저장소 폴더(.git 이 있는 폴더)를 다시 골라서 실행해 주세요.");
    }
    if has(m, &["저장소 폴더가 없"]) {
        return g("저장소 폴더가 비었거나 없는 경로입니다.", "저장소 폴더를 고르거나 경로를 바로잡은 뒤 다시 실행해 주세요.");
    }
    if has(m, &["번들 파일이 없"]) {
        return g("번들 파일이 지정한 위치에 없습니다.", "번들 파일 경로를 확인하고 다시 골라 주세요.");
    }
    if has(m, &["머지·리베이스", "진행 중인 상태"]) {
        return g(
            "저장소가 병합·리베이스 등 진행 중인 상태입니다.",
            "Git 도구에서 진행 중인 작업을 먼저 끝내거나 취소한 뒤 다시 실행해 주세요.",
        );
    }
    if has(m, &["작업 파일 상태를 확인하지 못"]) {
        return g(
            "저장소의 작업 파일 상태(git status)를 읽지 못했습니다.",
            "저장소 폴더가 올바른지, git 이 정상으로 도는지 확인한 뒤 다시 실행해 주세요. 아무것도 바꾸지 않았습니다.",
        );
    }
    if has(m, &["커밋되지 않은 변경", "수정 중인 파일"]) {
        return g(
            "커밋하지 않은 변경(수정 중인 파일)이 있습니다.",
            "의도한 변경은 커밋하고, 아니면 치우거나 되돌린 뒤 다시 실행해 주세요.",
        );
    }
    if has(m, &["다른 작업 트리", "다른 작업트리", "다른 작업 폴더"]) {
        return g(
            "그 브랜치가 다른 작업 폴더에서 작업 중입니다.",
            "그 작업 폴더에서 다른 브랜치로 옮기거나 그 작업 폴더를 정리한 뒤 다시 실행해 주세요.",
        );
    }
    if has(m, &["대소문자"]) {
        return g(
            "대소문자만 다른 같은 이름의 브랜치가 이미 있습니다.",
            "로컬 브랜치 이름을 번들의 이름과 똑같이 맞춘 뒤 다시 실행해 주세요.",
        );
    }
    if has(m, &["규칙에 맞지 않"]) {
        return g(
            "브랜치 이름이 규칙에 맞지 않습니다.",
            "사용법 탭의 이름 규칙에 맞게 브랜치 이름을 고쳐 다시 실행해 주세요.",
        );
    }
    if has(m, &["갈라져", "빨리감기", "앞선 커밋이 있"]) {
        return g(
            "저장소와 번들의 이력이 갈라졌거나 저장소 쪽이 더 앞서 있어 덮어쓸 수 없습니다.",
            "원본에서 직접 커밋했다면 원본 저장소를 작업 PC 로 가져가 기준 저장소를 교체하고, 리베이스했다면 새 브랜치 이름으로 다시 내보내 주세요.",
        );
    }
    if has(m, &["기대는 커밋이 저장소에 없다", "먼저 적용했는지", "공통 조상이 없"]) {
        return g(
            "이 번들이 기대는 앞선 커밋이 저장소에 없습니다(앞선 번들이 빠졌거나 다른 저장소용 번들입니다).",
            "같은 브랜치의 이전 번들을 먼저 적용하거나, 올바른 저장소를 골랐는지 확인해 주세요. 안 되면 전체를 담은 번들로 다시 만들어 주세요.",
        );
    }
    if has(m, &["버전을 확인하지 못했", "이상이 필요"]) || lower.contains("git version") {
        return g("쓸 수 있는 git 버전이 아닙니다.", "요구 버전 이상의 git 으로 올리거나 PATH 의 git 경로를 확인한 뒤 다시 실행해 주세요.");
    }
    if has(m, &["서버에 연결", "GitLab 인증", "네트워크", "서버 브랜치 목록", "서버 브랜치를 읽"]) {
        return g(
            "서버에 연결하지 못했거나 인증에 실패했습니다.",
            "네트워크와 GitLab 인증(토큰·계정)을 확인하고, 원본 PC(서버에 연결되는 PC)에서 실행해야 하는 작업인지도 살펴 주세요.",
        );
    }
    // 번들 깨짐은 번들 검증(git bundle verify) 실패일 때만 보인다. 다른 '읽지 못했다'류는 기본 안내로 둔다.
    if has(m, &["검증에 실패", "파일이 깨졌거나 번들이 아닙"]) {
        return g(
            "번들 검증(git bundle verify)에 실패했습니다. 파일이 깨졌을 수 있습니다.",
            "번들 파일을 다시 복사하거나 다시 만들어 온 뒤 실행해 주세요. 전송 중 손상이 의심되면 크기와 파일 고유값(해시)을 확인해 주세요.",
        );
    }
    if has(m, &["번들이 아닙니다", "번들이 아니다"]) {
        return g("고른 번들의 종류가 이 작업과 맞지 않습니다.", "자동 판별로 적용하거나 알맞은 종류의 번들을 골라 주세요.");
    }
    if has(m, &["브랜치가 없"]) {
        return g("지정한 브랜치가 저장소에 없습니다.", "브랜치 이름을 확인하거나 저장소를 다시 고른 뒤 실행해 주세요.");
    }

    let first = m.lines().next().unwrap_or("").trim();
    Guide {
        reason: if first.is_empty() { "멈춘 이유가 문구에 없습니다.".to_string() } else { first.to_string() },
        next: "메시지를 확인하고 원인을 고친 뒤 다시 실행해 주세요. 바뀐 브랜치·태그가 있으면 기록 창의 되돌리기로 복원할 수 있습니다.".to_string(),
    }
}
